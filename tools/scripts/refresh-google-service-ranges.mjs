#!/usr/bin/env node
// Regenerates apps/backend/src/runtime/googleServiceRanges.ts from Google's published
// address lists: the ranges in goog.json that cloud.json does not hand to Cloud customers.
// Firebase Hosting forwards rewritten requests to Cloud Run from these ranges, so the backend
// treats them as the Hosting hop of its trusted proxy chain (docs/client-address.md).
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { isIPv4 } from 'node:net'

const GOOGLE_RANGES = 'https://www.gstatic.com/ipranges/goog.json'
const CLOUD_RANGES = 'https://www.gstatic.com/ipranges/cloud.json'
const output = fileURLToPath(
    new URL('../../apps/backend/src/runtime/googleServiceRanges.ts', import.meta.url)
)

async function fetchPrefixes(url) {
    const response = await fetch(url)
    if (!response.ok) throw new Error(`${url} answered ${response.status}`)
    const body = await response.json()
    return {
        creationTime: body.creationTime,
        prefixes: body.prefixes.map((entry) => entry.ipv4Prefix ?? entry.ipv6Prefix)
    }
}

function parseAddress(address) {
    if (isIPv4(address)) {
        return { bits: 32n, value: address.split('.').reduce((v, o) => (v << 8n) + BigInt(o), 0n) }
    }
    const [head, tail = ''] = address.split('::')
    const headGroups = head ? head.split(':') : []
    const tailGroups = tail ? tail.split(':') : []
    const groups = [
        ...headGroups,
        ...Array(8 - headGroups.length - tailGroups.length).fill('0'),
        ...tailGroups
    ]
    return { bits: 128n, value: groups.reduce((v, g) => (v << 16n) + BigInt(`0x${g || '0'}`), 0n) }
}

function toInterval(prefix) {
    const [address, length] = prefix.split('/')
    const { bits, value } = parseAddress(address)
    const hostBits = bits - BigInt(length)
    const start = (value >> hostBits) << hostBits
    return { bits, start, end: start + (1n << hostBits) - 1n }
}

function subtract(intervals, holes) {
    let remaining = intervals
    for (const hole of holes) {
        remaining = remaining.flatMap((interval) => {
            if (
                interval.bits !== hole.bits ||
                hole.end < interval.start ||
                hole.start > interval.end
            ) {
                return [interval]
            }
            const pieces = []
            if (hole.start > interval.start) {
                pieces.push({ ...interval, end: hole.start - 1n })
            }
            if (hole.end < interval.end) {
                pieces.push({ ...interval, start: hole.end + 1n })
            }
            return pieces
        })
    }
    return remaining
}

function formatAddress(value, bits) {
    if (bits === 32n) {
        return [24n, 16n, 8n, 0n].map((shift) => String((value >> shift) & 255n)).join('.')
    }
    const groups = []
    for (let shift = 112n; shift >= 0n; shift -= 16n) {
        groups.push(((value >> shift) & 0xffffn).toString(16))
    }
    return groups.join(':').replace(/(^|:)0(:0)+(:|$)/, '::')
}

function toPrefixes({ bits, start, end }) {
    const prefixes = []
    let cursor = start
    while (cursor <= end) {
        let hostBits = 0n
        while (
            hostBits < bits &&
            (cursor & ((1n << (hostBits + 1n)) - 1n)) === 0n &&
            cursor + (1n << (hostBits + 1n)) - 1n <= end
        ) {
            hostBits += 1n
        }
        prefixes.push(`${formatAddress(cursor, bits)}/${bits - hostBits}`)
        cursor += 1n << hostBits
    }
    return prefixes
}

const google = await fetchPrefixes(GOOGLE_RANGES)
const cloud = await fetchPrefixes(CLOUD_RANGES)
const services = subtract(google.prefixes.map(toInterval), cloud.prefixes.map(toInterval))
    .sort((a, b) => (a.bits === b.bits ? (a.start < b.start ? -1 : 1) : a.bits < b.bits ? -1 : 1))
    .flatMap(toPrefixes)

const lines = [
    `// Generated by tools/scripts/refresh-google-service-ranges.mjs; do not edit by hand.`,
    `// Source lists published ${google.creationTime} (goog.json) and ${cloud.creationTime} (cloud.json).`,
    `export const googleServiceRanges: readonly string[] = [`,
    ...services.map((prefix) => `    '${prefix}',`),
    `]`,
    ``
]
await writeFile(output, lines.join('\n').replace(/,\n\]/, '\n]'))
console.log(`${services.length} Google service prefixes written to ${output}`)
