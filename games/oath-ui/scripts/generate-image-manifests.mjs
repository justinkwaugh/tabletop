#!/usr/bin/env node
// Writes `src/lib/images/imageManifest.generated.ts` as static imports, because the rollup bundle
// cannot resolve `import.meta.glob`. Runs before `build` and `bundle`.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const imagesDir = path.join(here, '..', 'src', 'lib', 'images')
const outFile = path.join(imagesDir, 'imageManifest.generated.ts')

const GROUPS = [
    { name: 'cardFiles', dir: 'cards', exts: ['.jpg'], recursive: true },
    { name: 'backFiles', dir: 'backs', exts: ['.jpg'], recursive: false },
    { name: 'pieceFiles', dir: 'pieces', exts: ['.png'], recursive: false },
    { name: 'actionFiles', dir: 'actions', exts: ['.png'], recursive: false },
    { name: 'diceFiles', dir: 'dice', exts: ['.jpg'], recursive: false },
    { name: 'playerBoardFiles', dir: 'playerBoards', exts: ['.jpg'], recursive: false },
    { name: 'tileFiles', dir: 'tiles', exts: ['.png', '.jpg'], recursive: false },
    { name: 'bannerFiles', dir: 'banners', exts: ['.jpg'], recursive: false }
]

function walk(dir, recursive) {
    if (!fs.existsSync(dir)) return []
    const out = []
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name)
        if (entry.isDirectory()) {
            if (recursive) out.push(...walk(full, true))
        } else {
            out.push(full)
        }
    }
    return out
}

let ident = 0
const importLines = []
const groupBlocks = []
let total = 0

for (const group of GROUPS) {
    const root = path.join(imagesDir, group.dir)
    const files = walk(root, group.recursive)
        .filter((f) => group.exts.includes(path.extname(f).toLowerCase()))
        // Sorted so the generated file is stable and diffs stay readable.
        .sort((a, b) => a.localeCompare(b))

    const entries = files.map((f) => {
        // Relative to `images/`, `./`-prefixed, with POSIX separators.
        const rel = './' + path.relative(imagesDir, f).split(path.sep).join('/')
        const name = `img${ident++}`
        importLines.push(`import ${name} from '${rel}'`)
        return `    '${rel}': ${name}`
    })

    total += entries.length
    groupBlocks.push(
        `/** ${entries.length} file${entries.length === 1 ? '' : 's'} under \`${group.dir}/\`. */\n` +
            `export const ${group.name}: Record<string, string> = {\n${entries.join(',\n')}\n}`
    )
}

// Emitted in the repository's Prettier style, so the file passes `prettier --check` as written.
const banner = `// Generated by \`scripts/generate-image-manifests.mjs\` before every build and bundle; ${total} assets.
`

fs.writeFileSync(
    outFile,
    banner + importLines.join('\n') + '\n\n' + groupBlocks.join('\n\n') + '\n'
)
console.log(`generate-image-manifests: ${total} assets -> ${path.relative(process.cwd(), outFile)}`)
