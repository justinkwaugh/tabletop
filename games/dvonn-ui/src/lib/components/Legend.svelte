<script lang="ts">
    import type { Attachment } from 'svelte/attachments'
    import { Popover } from 'flowbite-svelte'
    import { getGameSession } from '$lib/model/sessionContext.svelte.js'
    import { DvonnVersion, versionFromConfig } from '@tabletop/dvonn'

    // A (?) chip that opens a short rules reference.
    let { reference }: { reference: string } = $props()

    const session = getGameSession()
    const uid = $props.id()
    const chipId = `legend-${uid}`
    const OFFSET = 6

    const version = $derived(versionFromConfig(session.game.config))

    // Holds the panel to the screen below the header, so it never runs off a short phone. The
    // popover mounts its contents only while open, so this runs each time it opens.
    const fitBelowHeader: Attachment<HTMLElement> = (node) => {
        const fit = () => {
            // Measured from the header it opens under: the panel itself is placed a frame later.
            const below = document.querySelector(reference)?.getBoundingClientRect().bottom ?? 0
            // The visible area: a page wider than the phone stretches innerHeight past it.
            const view = window.visualViewport
            const bottom = view ? view.offsetTop + view.height : window.innerHeight
            const room = bottom - below - OFFSET - 8
            node.style.maxHeight = `${Math.max(160, Math.min(640, room))}px`
        }
        const frame = requestAnimationFrame(fit)
        const view = window.visualViewport ?? window
        view.addEventListener('resize', fit)
        return () => {
            cancelAnimationFrame(frame)
            view.removeEventListener('resize', fit)
        }
    }
</script>

<button type="button" id={chipId} class="chip" aria-label="Rules reference">?</button>
<Popover
    {reference}
    triggeredBy={`#${chipId}`}
    trigger="click"
    placement="bottom-end"
    offset={OFFSET}
    arrow={false}
    class="z-50 border-0 bg-transparent shadow-none dark:border-0 dark:bg-transparent"
    classes={{ content: 'p-0' }}
>
    <div class="legend" {@attach fitBelowHeader}>
        <section>
            <h3>Moving</h3>
            <ul>
                <li>
                    Move one stack you control (your colour on top) in a straight line exactly as
                    many spaces as it is tall. It must land on another stack, and may pass over
                    anything on the way.
                </li>
                <li>
                    A stack with all six neighbours filled can’t move. A lone DVONN piece never
                    moves, but a stack holding one moves with whoever controls it.
                </li>
                <li>A player with no move passes, and moves again once a move opens up.</li>
            </ul>
        </section>
        <section>
            <h3>Cut off</h3>
            <p>
                After every move, each stack with no chain of stacks linking it to a DVONN piece
                leaves the board, whoever owns it.
            </p>
        </section>
        {#if version === DvonnVersion.Standard}
            <section>
                <h3>Placing</h3>
                <p>
                    The three DVONN pieces go down first, then each player places their own pieces
                    in turn until the board is full. White places last and moves first.
                </p>
            </section>
        {/if}
        <section>
            <h3>Winning</h3>
            <p>
                When neither player can move, each counts the pieces in the stacks they control.
                More pieces wins; equal counts draw.
            </p>
        </section>
    </div>
</Popover>

